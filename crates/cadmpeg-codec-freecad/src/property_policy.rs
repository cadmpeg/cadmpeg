/// Only fields emitted by this codec are projection framing. A user's property
/// sharing a prefix remains content and receives an ordinary neutral home.
pub(crate) fn is_projection_metadata(property: &crate::native::PropertyRecord) -> bool {
    if !matches!(&property.body, crate::native::PropertyBody::Persisted { dynamic: Some(dynamic), .. } if dynamic.group == "CADIR")
    {
        return false;
    }
    if matches!(
        property.name.as_str(),
        "CadmpegBodyNames"
            | "CadmpegFeatureOrdinal"
            | "CadmpegFeatureSourceTag"
            | "CadmpegHasFeatureSourceTag"
            | "CadmpegOccurrenceOrdinal"
            | "CadmpegParameterOrdinals"
            | "CadmpegProductLabel"
            | "CadmpegProductSourceName"
            | "CadmpegHasProductDefinition"
            | "CadmpegHasProductOccurrence"
            | "CadmpegOccurrenceName"
            | "CadmpegOccurrenceVisible"
            | "CadmpegOccurrenceLocalPlacement"
            | "CadmpegHasLinkedPrototypePlacement"
            | "CadmpegLinkedPrototypePlacement"
            | "CadmpegControlLinks"
            | "CadmpegParameterNames"
    ) {
        return true;
    }
    let Some(rest) = property.name.strip_prefix("CadmpegBody") else {
        return false;
    };
    let digits = rest.bytes().take_while(u8::is_ascii_digit).count();
    digits != 0
        && matches!(
            &rest[digits..],
            "ColorPresent" | "Red" | "Green" | "Blue" | "Alpha" | "VisiblePresent" | "Visible"
        )
}
