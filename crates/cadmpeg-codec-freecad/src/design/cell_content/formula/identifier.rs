//! Unicode scalar ranges of L, M and N in `FreeCAD` `Expression.l` at
//! 4fd3bf320d9566a27e60069fc8387448aaa3a094.

#[derive(Clone, Copy)]
enum Category {
    Letter,
    Mark,
    Number,
}

use Category::{Letter, Mark, Number};

fn category(ch: char) -> Option<Category> {
    let scalar = u32::from(ch);
    let at = RANGES.partition_point(|&(_, end, _)| end < scalar);
    let &(start, _, category) = RANGES.get(at)?;
    (start <= scalar).then_some(category)
}

pub(super) fn is_letter(ch: char) -> bool {
    matches!(category(ch), Some(Letter))
}

/// The identifier or function-name prefix, including marks after a letter.
/// Expression.l gives an initial underscore and internal @ to identifiers.
pub(super) fn prefix(text: &str, function: bool) -> usize {
    let mut at = 0;
    let mut marks = false;
    for ch in text.chars() {
        match category(ch) {
            Some(Letter) => marks = true,
            Some(Mark) if marks => {}
            Some(Number) if at != 0 => marks = false,
            _ if ch == '_' && (!function || at != 0) => marks = false,
            _ if ch == '@' && !function && at != 0 => marks = false,
            _ => break,
        }
        at += ch.len_utf8();
    }
    at
}

