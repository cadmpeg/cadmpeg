impl TryFrom<DesignDimensionLocusGroupWire> for DesignDimensionLocusGroup {
    type Error = String;
    fn try_from(wire: DesignDimensionLocusGroupWire) -> Result<Self, String> {
        if wire.return_members.len() != wire.loci.len() {
            return Err("return_members must match loci".into());
        }
        let mut loci = Vec::new();
        loci.try_reserve_exact(wire.loci.len())
            .map_err(|error| error.to_string())?;
        loci.extend(
            wire.loci
                .into_iter()
                .zip(wire.return_members)
                .map(|(locus, value)| DesignDimensionLocus {
                    returned: Located {
                        value,
                        offset: None,
                    },
                    geometry_record_index: locus.geometry_record_index,
                    geometry_reference_offset: None,
                    role: locus.role,
                    role_offset: None,
                }),
        );
        Ok(Self {
            id: wire.id,
            companion_record_index: wire.companion_record_index,
            byte_offset: None,
            class_tag: wire.class_tag.try_into()?,
            record_index: wire.record_index,
            frame_length: None,
            loci,
            owner_reference: wire.owner_reference,
            owner_reference_offset: None,
            owner_role: wire.owner_role,
            owner_role_offset: None,
            state: wire.state,
            state_offset: None,
            next_class_tag: wire.next_class_tag.try_into()?,
            next_record_index: wire.next_record_index,
            next_byte_offset: None,
        })
    }
}
