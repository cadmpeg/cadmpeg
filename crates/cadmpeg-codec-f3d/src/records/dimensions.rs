impl Serialize for DesignDimensionLocusPair {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        #[derive(Serialize)]
        struct WireRef<'a> {
            id: &'a str,
            companion_record_index: u32,
            governing_companion_record_index: u32,
            class_tag: &'a str,
            record_index: u32,
            #[serde(skip_serializing_if = "Option::is_none")]
            opaque_index: Option<u32>,
            first_geometry_record_index: u32,
            first_role: u32,
            second_geometry_record_index: u32,
            second_role: u32,
            paired_class_tag: &'a str,
        }
        let [first, second] = self.loci();
        WireRef {
            id: &self.id,
            companion_record_index: self.companion_record_index,
            governing_companion_record_index: self.governing_companion_record_index,
            class_tag: self.class_tag.as_str(),
            record_index: self.record_index,
            opaque_index: self.opaque_index().map(|field| field.value),
            first_geometry_record_index: first.geometry_index(),
            first_role: first.role,
            second_geometry_record_index: second.geometry_index(),
            second_role: second.role,
            paired_class_tag: self.paired_class_tag.as_str(),
        }
        .serialize(serializer)
    }
}
impl TryFrom<DesignDimensionLocusPairWire> for DesignDimensionLocusPair {
    type Error = String;
    fn try_from(wire: DesignDimensionLocusPairWire) -> Result<Self, String> {
        let first = match (
            wire.opaque_index,
            NonZeroU32::new(wire.first_geometry_record_index),
        ) {
            (None, None) => DimensionFirstLocus::Null,
            (Some(opaque_index), Some(record_index)) => DimensionFirstLocus::Geometry {
                opaque_index,
                record_index,
            },
            _ => return Err(
                "opaque_index is present exactly when first_geometry_record_index names geometry"
                    .into(),
            ),
        };
        Ok(Self {
            id: wire.id,
            companion_record_index: wire.companion_record_index,
            governing_companion_record_index: wire.governing_companion_record_index,
            byte_offset: None,
            class_tag: wire.class_tag.try_into()?,
            record_index: wire.record_index,
            frame_length: None,
            first,
            second_geometry_record_index: NonZeroU32::new(wire.second_geometry_record_index)
                .ok_or(
                    "second_geometry_record_index must name an indexed sketch-geometry record",
                )?,
            roles: [wire.first_role, wire.second_role],
            paired_class_tag: wire.paired_class_tag.try_into()?,
        })
    }
}
