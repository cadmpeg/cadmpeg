impl DesignDimensionAnnotationFrame {
    pub(crate) fn authored(
        content: DesignDimensionAnnotationContent,
    ) -> Result<Self, cadmpeg_core::CodecError> {
        Self::from_content(content).map_err(cadmpeg_core::CodecError::malformed)
    }
    fn from_content(content: DesignDimensionAnnotationContent) -> Result<Self, String> {
        if content.operands.is_empty() {
            return Err("operands must not be empty".into());
        }
        let mut counts = std::collections::BTreeMap::<NonZeroU32, usize>::new();
        for index in content
            .operands
            .iter()
            .filter_map(|operand| operand.geometry_record_index)
        {
            *counts.entry(index).or_default() += 1;
        }
        for index in &content.return_members {
            let Some(count) = counts.get_mut(index) else {
                return Err("return_members disagree with operands geometry indices".into());
            };
            if *count == 0 {
                return Err("return_members disagree with operands geometry indices".into());
            }
            *count -= 1;
        }
        if counts.values().any(|count| *count != 0) {
            return Err("return_members disagree with operands geometry indices".into());
        }
        Ok(Self {
            id: content.id,
            companion_record_index: content.companion_record_index,
            governing_companion_record_index: content.governing_companion_record_index,
            byte_offset: None,
            class_tag: content.class_tag,
            record_index: content.record_index,
            frame_length: None,
            operands: content.operands,
            entity_genesis: content.entity_genesis,
            annotation_bytes: None,
            governing_owner_record_index: content.governing_owner_record_index,
            return_members: content.return_members,
            paired_class_tag: content.paired_class_tag,
            owner_reference: content.owner_reference,
        })
    }
    pub(crate) fn try_new(
        draft: DesignDimensionAnnotationFrameDraft,
    ) -> Result<Self, cadmpeg_core::CodecError> {
        Self::try_new_inner(draft).map_err(cadmpeg_core::CodecError::malformed)
    }
    fn try_new_inner(draft: DesignDimensionAnnotationFrameDraft) -> Result<Self, String> {
        if draft.operands.is_empty() {
            return Err("operands must not be empty".into());
        }
        let operand_bytes = u64::try_from(draft.operands.len())
            .ok()
            .and_then(|count| count.checked_mul(15))
            .ok_or("operands length overflows frame offsets")?;
        let annotation_byte_offset = draft
            .byte_offset
            .checked_add(24)
            .and_then(|offset| offset.checked_add(operand_bytes))
            .and_then(|offset| offset.checked_add(57))
            .ok_or("annotation_byte_offset overflows")?;
        let governing_owner_reference_offset = u64::try_from(draft.annotation_bytes.len())
            .ok()
            .and_then(|len| annotation_byte_offset.checked_add(len))
            .and_then(|offset| offset.checked_add(1))
            .ok_or("governing_owner_reference_offset overflows")?;
        let paired_byte_offset = draft
            .byte_offset
            .checked_add(draft.frame_length)
            .ok_or("paired_byte_offset overflows")?;
        let owner_reference_offset = paired_byte_offset
            .checked_add(20)
            .ok_or("owner_reference_offset overflows")?;
        if draft.annotation_byte_offset != annotation_byte_offset {
            return Err("annotation_byte_offset disagrees with frame layout".into());
        }
        if draft.governing_owner_reference_offset != governing_owner_reference_offset {
            return Err("governing_owner_reference_offset disagrees with frame layout".into());
        }
        if draft.paired_byte_offset != paired_byte_offset {
            return Err("paired_byte_offset disagrees with frame layout".into());
        }
        if draft.owner_reference_offset != owner_reference_offset {
            return Err("owner_reference_offset disagrees with frame layout".into());
        }
        for (ordinal, operand) in draft.operands.iter().enumerate() {
            let start = draft.byte_offset + 24 + u64_from_index(ordinal) * 15;
            if operand.geometry_reference_offset != Some(start + 1)
                || operand.role_offset != Some(start + 11)
            {
                return Err(
                    "operands geometry_reference_offset or role_offset disagrees with frame layout"
                        .into(),
                );
            }
        }
        for (ordinal, member) in draft.return_members.iter().enumerate() {
            let expected = u64::try_from(ordinal)
                .ok()
                .and_then(|ordinal| ordinal.checked_mul(11))
                .and_then(|delta| governing_owner_reference_offset.checked_add(delta))
                .and_then(|offset| offset.checked_add(15))
                .ok_or("return_member_offsets overflow")?;
            if member.offset != expected {
                return Err("return_member_offsets disagree with frame layout".into());
            }
        }

        let byte_offset = draft.byte_offset;
        let frame_length = draft.frame_length;
        let annotation_frame = SourceFrame::from(draft.annotation_bytes);
        let mut content = Self::from_content(DesignDimensionAnnotationContent {
            id: draft.id,
            companion_record_index: draft.companion_record_index,
            governing_companion_record_index: draft.governing_companion_record_index,
            class_tag: draft.class_tag,
            record_index: draft.record_index,
            operands: draft
                .operands
                .into_iter()
                .map(|operand| DesignDimensionAnnotationLocus {
                    geometry_record_index: operand.geometry_record_index,
                    role: operand.role,
                })
                .collect(),
            entity_genesis: draft.entity_genesis,
            governing_owner_record_index: draft.governing_owner_record_index,
            return_members: draft
                .return_members
                .into_iter()
                .map(|member| member.value)
                .collect(),
            paired_class_tag: draft.paired_class_tag,
            owner_reference: draft.owner_reference,
        })?;
        content.byte_offset = Some(byte_offset);
        content.frame_length = Some(frame_length);
        content.annotation_bytes = Some(annotation_frame);
        Ok(content)
    }
    pub(crate) fn byte_offset(&self) -> Option<u64> {
        self.byte_offset
    }
    pub(crate) fn operands(&self) -> &[DesignDimensionAnnotationLocus] {
        &self.operands
    }
    pub(crate) fn annotation_byte_offset(&self) -> Option<u64> {
        self.byte_offset?
            .checked_add(24)?
            .checked_add(u64_from_index(self.operands.len()).checked_mul(15)?)?
            .checked_add(57)
    }
    fn governing_owner_reference_offset(&self) -> Option<u64> {
        self.annotation_byte_offset()?
            .checked_add(self.annotation_bytes.as_ref()?.byte_len())?
            .checked_add(1)
    }
    pub(crate) fn paired_byte_offset(&self) -> Option<u64> {
        self.byte_offset?.checked_add(self.frame_length?)
    }
    fn owner_reference_offset(&self) -> Option<u64> {
        self.paired_byte_offset()?.checked_add(20)
    }
    #[cfg(test)]
    pub(crate) fn into_draft(self) -> Result<DesignDimensionAnnotationFrameDraft, String> {
        let byte_offset = self
            .byte_offset
            .ok_or("source annotation position is unavailable")?;
        let frame_length = self
            .frame_length
            .ok_or("source annotation frame length is unavailable")?;
        let annotation_byte_offset = self
            .annotation_byte_offset()
            .ok_or("source annotation span is unavailable")?;
        let governing_owner_reference_offset = self
            .governing_owner_reference_offset()
            .ok_or("source governing-owner position is unavailable")?;
        let paired_byte_offset = self
            .paired_byte_offset()
            .ok_or("source paired-annotation position is unavailable")?;
        let owner_reference_offset = self
            .owner_reference_offset()
            .ok_or("source annotation-owner position is unavailable")?;
        let annotation_bytes = self
            .annotation_bytes
            .as_ref()
            .and_then(SourceFrame::data)
            .ok_or("source annotation bytes are unavailable")?
            .to_vec();
        Ok(DesignDimensionAnnotationFrameDraft {
            id: self.id,
            companion_record_index: self.companion_record_index,
            governing_companion_record_index: self.governing_companion_record_index,
            byte_offset,
            class_tag: self.class_tag,
            record_index: self.record_index,
            frame_length,
            operands: self
                .operands
                .into_iter()
                .enumerate()
                .map(|(ordinal, operand)| DesignDimensionAnnotationOperand {
                    geometry_record_index: operand.geometry_record_index,
                    role: operand.role,
                    geometry_reference_offset: Some(
                        byte_offset + 25 + u64_from_index(ordinal) * 15,
                    ),
                    role_offset: Some(byte_offset + 35 + u64_from_index(ordinal) * 15),
                })
                .collect(),
            entity_genesis: self.entity_genesis,
            annotation_bytes,
            annotation_byte_offset,
            governing_owner_record_index: self.governing_owner_record_index,
            governing_owner_reference_offset,
            return_members: self
                .return_members
                .into_iter()
                .enumerate()
                .map(|(ordinal, value)| Located {
                    value,
                    offset: governing_owner_reference_offset + 15 + u64_from_index(ordinal) * 11,
                })
                .collect(),
            paired_class_tag: self.paired_class_tag,
            paired_byte_offset,
            owner_reference: self.owner_reference,
            owner_reference_offset,
        })
    }
}
