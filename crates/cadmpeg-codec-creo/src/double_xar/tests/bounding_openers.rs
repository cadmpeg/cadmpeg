#[test]
fn seven_byte_bounding_openers_complete_model_tables() {
    for ((count, body), openers) in [
        (MIC_CLIP, [0x46, 0xa8, 0x46, 0x2d, 0x2d, 0x2d]),
        (THYRISTER, [0x46, 0x46, 0xa5, 0x2d, 0x2d, 0x9f]),
        (STC_08, [0x46, 0xdf, 0x41, 0xa3, 0x9c, 0x8a]),
        (STC_10, [0x4a, 0xbf, 0x46, 0x31, 0x2d, 0x2d]),
        (FTC_11, [0x46, 0x46, 0xdf, 0x2d, 0x2d, 0x9b]),
    ] {
        let tables = decode("Model_L05_PX", &framed(count, body));
        let [table] = tables.as_slice() else {
            panic!("one complete model table");
        };
        assert_eq!(table.logical_count, usize::from(count));
        assert_eq!(
            table
                .entries
                .iter()
                .map(DoubleXarSlot::logical_width)
                .sum::<usize>(),
            usize::from(count)
        );
        assert_eq!(
            table
                .entries
                .iter()
                .flat_map(DoubleXarSlot::raw)
                .copied()
                .collect::<Vec<_>>(),
            body
        );
        let bounds = table
            .entries
            .iter()
            .filter_map(|slot| match slot {
                DoubleXarSlot::ModelBound { value, raw } => Some((*value, raw.as_slice())),
                _ => None,
            })
            .collect::<Vec<_>>();
        assert_eq!(
            bounds.iter().map(|(_, raw)| raw[0]).collect::<Vec<_>>(),
            openers
        );
        for (value, raw) in bounds {
            if !matches!(raw[0], 0x2d | 0x41 | 0x46) {
                assert_eq!(raw.len(), 7);
                assert_eq!(value, None);
            }
        }
    }
}

#[test]
fn undecided_bounding_openers_leave_model_tables_unresolved() {
    for (count, body) in [CTC_03, HTC, STC_06] {
        assert!(decode("Model_L05_PX", &framed(count, body)).is_empty());
    }
}
