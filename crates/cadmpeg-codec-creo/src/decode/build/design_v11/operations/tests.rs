fn legacy(kind: &str, value: Value) -> LegacyOperation {
    let fields = serde_json::Map::from_iter([
        ("kind".to_owned(), Value::String(kind.to_owned())),
        ("value".to_owned(), value),
    ]);
    cadmpeg_core::serde_erase::json::from_value(Value::Object(fields)).expect("synthetic operation")
}

fn feature(key: u32) -> FeatureId {
    FeatureId::mint(format!("creo:model:feature#{key}")).expect("feature id")
}

fn sketch() -> SketchId {
    SketchId::mint("creo:model:sketch#40").expect("sketch id")
}

fn unit(value: [f64; 3]) -> UnitVector3 {
    UnitVector3::normalized(cadmpeg_ir::math::Vector3::new(value[0], value[1], value[2]))
        .expect("unit")
}

/// A section frame whose normal is +z.
fn frame() -> FrameValue {
    FrameValue {
        origin: FinitePoint3::ZERO,
        x_axis: unit([1.0, 0.0, 0.0]),
        y_axis: unit([0.0, 1.0, 0.0]),
        z_axis: unit([0.0, 0.0, 1.0]),
    }
}

/// Surface 7 and edge 9 are generated by feature 10, which precedes the
/// picking feature 50; surface 8 is generated by feature 50 itself.
fn names() -> Names {
    let mut scan = crate::test_support::empty_container_scan();
    let surface = |id, feature_id| crate::surface::SurfaceRow {
        id,
        kind: crate::surface::SurfaceKind::Plane,
        feature_id,
        reversed: false,
        boundary_type: crate::surface::BoundaryType::Code00,
        next_surface: 0,
        offset: 0,
    };
    scan.surfaces.rows.extend([surface(7, 10), surface(8, 50)]);
    scan.curves
        .topology_rows
        .push(crate::curve::CurveTopologyRow {
            id: 9,
            type_byte: 8,
            feature_id: 10,
            directions: [1, 0xf6],
            faces: [std::num::NonZeroU32::new(7), std::num::NonZeroU32::new(8)],
            next_edges: [9, 9],
            offset: 0,
        });
    let order = [feature(10), sketch_feature(), feature(50)];
    Names::new(&scan, order.iter())
}

fn sketch_feature() -> FeatureId {
    feature(40)
}

fn with_stated<T>(run: impl FnOnce(&Stated<'_>) -> T) -> T {
    let names = names();
    let sketch = sketch();
    let frame = frame();
    let stated = Stated {
        sketches: BTreeMap::from([(&sketch, Some(&frame))]),
        names: &names,
    };
    run(&stated)
}

fn project(operation: &LegacyOperation) -> Option<FeatureOperation> {
    let projected = with_stated(|stated| typed(operation, &feature(50), stated))?;
    let wire = cadmpeg_core::serde_erase::json::to_value(&projected).expect("v11 wire");
    let read: FeatureOperation =
        cadmpeg_core::serde_erase::json::from_value(wire).expect("v11 read");
    assert_eq!(projected, read);
    Some(projected)
}

fn extrude(direction: &Value, extent: &Value) -> LegacyOperation {
    legacy(
        "extrude",
        json!({
            "profile": {"kind": "planar", "value": {"kind": "sketch", "value": "creo:model:sketch#40"}},
            "direction": direction,
            "start": {"kind": "profile_plane"},
            "extent": extent,
            "op": "join",
            "solid": true,
        }),
    )
}

fn blind(length: f64) -> Value {
    json!({"termination": {"kind": "blind", "length": length}})
}

fn length(value: f64) -> Dimension<Length> {
    Dimension::Literal(Length::new(value).expect("length"))
}

#[test]
fn an_extrude_travels_along_its_section_normal_from_the_section_plane() {
    let operation = extrude(
        &json!({"kind": "explicit", "vector": [0.0, 0.0, -1.0]}),
        &json!({"kind": "one_sided", "side": blind(12.5)}),
    );
    let Some(FeatureOperation::Extrude(extrude)) = project(&operation) else {
        panic!("extrude");
    };
    assert!(matches!(
        extrude.profile.picks,
        Picks::Named(ref picks) if picks.as_slice()[0].target == PickTarget::Sketch(sketch())
    ));
    assert_eq!(
        extrude.direction,
        Some(ExtrudeDirection::ProfileNormal {
            reversed: Some(Dimension::Literal(true))
        })
    );
    assert_eq!(extrude.origin, Some(ExtrudeOrigin::ProfilePlane));
    assert_eq!(
        extrude.span,
        Some(Span::Between {
            start: Box::new(Limit::AtOrigin),
            end: Box::new(Limit::Amount(length(12.5))),
        })
    );
    assert_eq!(extrude.output.body, Some(BodyForm::Solid));
    assert_eq!(
        extrude.output.boolean,
        Some(Boolean::Apply {
            op: BooleanOp::Join,
            targets: None
        })
    );
}

#[test]
fn a_second_side_is_measured_against_the_travel() {
    let operation = extrude(
        &json!({"kind": "explicit", "vector": [0.0, 0.0, 2.0]}),
        &json!({"kind": "two_sided", "first": blind(8.0), "second": blind(3.0)}),
    );
    let Some(FeatureOperation::Extrude(extrude)) = project(&operation) else {
        panic!("extrude");
    };
    assert_eq!(
        extrude.span,
        Some(Span::Between {
            start: Box::new(Limit::Amount(length(-3.0))),
            end: Box::new(Limit::Amount(length(8.0))),
        })
    );
    assert_eq!(
        extrude.direction,
        Some(ExtrudeDirection::ProfileNormal {
            reversed: Some(Dimension::Literal(false))
        })
    );
}

#[test]
fn a_two_sided_revolve_negates_its_second_side() {
    let operation = legacy(
        "revolve",
        json!({
            "construction": {
                "kind": "resolved",
                "value": {
                    "profile": {"kind": "sketch", "value": "creo:model:sketch#40"},
                    "axis": {"origin": [0.0, 0.0, 0.0], "direction": [0.0, 1.0, 0.0]},
                    "extent": {
                        "kind": "two_sided",
                        "first": {"kind": "angle", "angle": 2.0},
                        "second": {"kind": "angle", "angle": 1.0},
                    },
                    "solid": true,
                },
            },
            "op": "new_body",
        }),
    );
    let Some(FeatureOperation::Revolve(revolve)) = project(&operation) else {
        panic!("revolve");
    };
    assert_eq!(
        revolve.span,
        Some(Span::Between {
            start: Box::new(Limit::Amount(Dimension::Literal(
                Angle::new(-1.0).expect("angle")
            ))),
            end: Box::new(Limit::Amount(Dimension::Literal(
                Angle::new(2.0).expect("angle")
            ))),
        })
    );
    assert!(
        revolve
            .axis
            .as_ref()
            .is_some_and(|axis| !axis.inputs.is_empty()),
        "{:?}",
        revolve.axis
    );
}

