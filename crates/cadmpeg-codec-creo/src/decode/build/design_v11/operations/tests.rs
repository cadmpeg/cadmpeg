#[test]
fn a_revolve_states_its_axis_and_angle() {
    let operation = legacy(
        "revolve",
        json!({
            "construction": {
                "kind": "resolved",
                "profile": {"kind": "sketch", "value": "creo:model:sketch#40"},
                "axis": {"origin": [0.0, 0.0, 0.0], "direction": [0.0, 1.0, 0.0]},
                "extent": {"kind": "one_sided", "termination": {"kind": "angle", "angle": 1.5}},
                "solid": true,
            },
            "op": "new_body",
        }),
    );
    let Some(FeatureOperation::Revolve(revolve)) = project(&operation) else {
        panic!("revolve");
    };
    assert_eq!(
        revolve.axis.and_then(|axis| axis.resolved).map(|axis| axis.direction),
        Some(unit([0.0, 1.0, 0.0]))
    );
    assert_eq!(
        revolve.span,
        Some(Span::Between {
            start: Box::new(Limit::AtOrigin),
            end: Box::new(Limit::Amount(Dimension::Literal(
                Angle::new(1.5).expect("angle")
            ))),
        })
    );
    assert_eq!(revolve.output.boolean, Some(Boolean::NewBody));
}

#[test]
fn a_round_picks_its_edges_by_their_producing_feature() {
    let operation = legacy(
        "fillet",
        json!({"groups": [{
            "edges": {"kind": "resolved", "edges": ["creo:visibgeom:edge#9"], "native": "creo:allfeatur:edgs_affected#50:9"},
            "radius": {"kind": "constant", "radius": 2.0},
        }]}),
    );
    let Some(FeatureOperation::Fillet(fillet)) = project(&operation) else {
        panic!("fillet");
    };
    let FilletSet::Edges { edges, section, .. } = &fillet.sets[0] else {
        panic!("edge set");
    };
    assert_eq!(
        section.size,
        Some(FilletSize::Radius(Dimension::Literal(
            PositiveLength::new(2.0).expect("radius")
        )))
    );
    let Picks::Named(picks) = &edges.picks else {
        panic!("named edges");
    };
    let pick = &picks.as_slice()[0];
    assert_eq!(
        pick.target,
        PickTarget::Entity(TopoName::Generated {
            kind: NameKind::Edge,
            feature: feature(10),
            role: None,
            generator: None,
            index: None,
        })
    );
    assert_eq!(pick.native, Some(super::super::names::native(9)));
    assert!(edges.native.is_some());
}

#[test]
fn a_hole_starts_on_a_face_its_own_feature_makes_by_native_name() {
    use cadmpeg_ir::features::holes;
    let operation = LegacyOperation::Hole {
        profile: None,
        profile_filter: None,
        face: Some(cadmpeg_ir::features::FaceSelection::Native(
            "creo:visibgeom:surface#8".to_owned(),
        )),
        direction: None,
        placements: Some(vec![holes::HolePlacement::Directed {
            position: FinitePoint3::ZERO,
            direction: cadmpeg_ir::features::FeatureDirection3::new(
                cadmpeg_ir::math::Vector3::new(0.0, 0.0, 1.0),
            )
            .expect("direction"),
        }]),
        shape: holes::HoleShape::new(
            holes::HoleConstruction::Form {
                kind: holes::HoleKind::Simple,
                specification: None,
            },
            None,
            PositiveLength::new(5.0),
        )
        .expect("shape"),
        extent: Some(cadmpeg_ir::features::LinearTermination::Blind {
            length: cadmpeg_ir::scalar::NonZeroLength::new(10.0).expect("depth"),
        }),
        bottom: Some(holes::HoleBottom::Flat),
        taper_angle: None,
        allow_multi_profile_faces: None,
    };
    let Some(FeatureOperation::Hole(hole)) = project(&operation) else {
        panic!("hole");
    };
    let start = hole.start.expect("start face");
    let Picks::Named(picks) = &start.picks else {
        panic!("named start");
    };
    assert_eq!(
        picks.as_slice()[0].target,
        PickTarget::Native { within: None }
    );
    assert!(matches!(hole.positions, HolePositions::Placed(ref points) if points.len() == 1));
    assert_eq!(hole.direction, None);
    let HoleShape::Bore(bore) = &hole.shape else {
        panic!("bore");
    };
    assert_eq!(bore.head, Some(HoleHead::Plain));
    assert_eq!(hole.extent, Some(Limit::Amount(length(10.0))));
}

#[test]
fn a_datum_plane_states_its_frame() {
    let operation = legacy(
        "datum_plane",
        json!({"frame": {"origin": [0.0, 0.0, 5.0], "normal": [0.0, 0.0, 1.0], "u_axis": [1.0, 0.0, 0.0]}}),
    );
    let Some(FeatureOperation::Datum(datum)) = project(&operation) else {
        panic!("datum");
    };
    let cadmpeg_ir::design::ops::datum::DatumElement::Plane(plane) = &datum.element else {
        panic!("plane");
    };
    assert!(plane.inputs.is_empty());
    assert_eq!(
        plane.resolved.as_ref().map(|plane| plane.normal),
        Some(unit([0.0, 0.0, 1.0]))
    );
}
