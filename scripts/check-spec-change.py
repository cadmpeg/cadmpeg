"""A pull request that edits the specification outside its generated Annex A changes no crate.

``docs/cadir-v11.md`` changes in a specification-only pull request from the
errata process (https://github.com/cadmpeg/cadmpeg/issues/209). The body of
Annex A, below the annex's opening paragraph, is generated by
``scripts/generate-annex-a.py --write`` and changes with the crates that
declare its types.

Usage: scripts/check-spec-change.py --base REV [--head REV]
Compares the two commits (``--head`` defaults to ``HEAD``). Exit status 0
passes, 1 reports the crate files of a pull request that also edits the
specification, 2 means Git could not compare the commits.
"""

from __future__ import annotations

import argparse
import importlib.util
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = "docs/cadir-v11.md"
CRATES = "crates/"
PROCESS = "https://github.com/cadmpeg/cadmpeg/issues/209"
MESSAGE = (f"{SPEC} changes outside the generated Annex A, and the pull request also changes "
           f"files under {CRATES}. The specification changes only in a specification-only pull "
           f"request from the errata process ({PROCESS}). Move the specification edit to its own "
           "pull request; a regenerated Annex A body (scripts/generate-annex-a.py --write) is exempt.")

_ANNEX = importlib.util.spec_from_file_location(
    "generate_annex_a", Path(__file__).with_name("generate-annex-a.py"))
assert _ANNEX and _ANNEX.loader
annex = importlib.util.module_from_spec(_ANNEX)
_ANNEX.loader.exec_module(annex)


def handwritten(spec: str | None) -> str | None:
    """The specification without the generated Annex A body, or None when the file is absent."""
    if spec is None:
        return None
    try:
        head, _ = annex.split_annex(spec)
    except annex.ShapeError:
        return spec
    return head


def crate_changes(paths: list[str], base_spec: str | None, spec: str | None) -> list[str]:
    """The changed crate files when the specification also changes outside Annex A's body."""
    if handwritten(base_spec) == handwritten(spec):
        return []
    return sorted(path for path in paths if path.startswith(CRATES))


def git(*arguments: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *arguments], cwd=ROOT, capture_output=True, text=True,
                          errors="replace")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--base", required=True, help="the commit the pull request merges into")
    parser.add_argument("--head", default="HEAD", help="the pull request's commit (default HEAD)")
    args = parser.parse_args(argv)
    diff = git("diff", "--no-renames", "--name-only", "-z", args.base, args.head)
    if diff.returncode:
        print(f"check-spec-change: {diff.stderr.strip()}", file=sys.stderr)
        return 2
    paths = [path for path in diff.stdout.split("\0") if path]
    if SPEC not in paths:
        print(f"check-spec-change: ok ({SPEC} unchanged)")
        return 0

    def show(revision: str) -> str | None:
        process = git("show", f"{revision}:{SPEC}")
        return process.stdout if process.returncode == 0 else None

    base_spec, spec = show(args.base), show(args.head)
    if handwritten(base_spec) == handwritten(spec):
        print("check-spec-change: ok (only the generated Annex A body changes)")
        return 0
    crates = crate_changes(paths, base_spec, spec)
    if not crates:
        print("check-spec-change: ok (a specification-only change)")
        return 0
    print(f"{SPEC}: spec_change_with_crates: {MESSAGE}")
    for path in crates:
        print(f"  {path}")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
